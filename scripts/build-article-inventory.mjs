// Emits the full article inventory for the final report: every article with its
// slug, category, associated app, primary intent and keyword cluster.
//
// Generated rather than typed, so the report cannot disagree with the content.
//
// Run: node scripts/build-article-inventory.mjs

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const CONTENT = join(ROOT, 'content', 'blog');
const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/;

/**
 * The 39 articles that existed as gated drafts before this pass. Listed
 * explicitly because "published on the release date" cannot distinguish them
 * from the 100 written in the same pass — only the repository history can, and
 * a hard-coded list is more durable than a git query in a generated report.
 */
const PREVIOUSLY_GATED = new Set([
  'android-video-players-compared', 'best-offline-arcade-games-android',
  'best-offline-sports-games-android', 'best-sports-manager-games-for-short-sessions',
  'cantonese-tones-explained', 'cantonese-vs-mandarin-differences',
  'career-mode-vs-franchise-mode', 'digital-coloring-techniques',
  'football-positions-explained-for-drafting', 'history-of-shoot-em-up-games',
  'hockey-line-combinations-explained', 'hockey-positions-explained',
  'how-fantasy-draft-strategy-works', 'how-long-does-it-take-to-learn-russian',
  'how-soccer-league-tables-work', 'how-sports-simulation-engines-work',
  'is-thai-hard-to-learn', 'keto-macros-explained', 'khmer-script-explained',
  'language-learning-apps-compared', 'low-carb-tracking-apps-compared',
  'major-eras-of-world-history', 'malay-pronunciation-guide',
  'mma-weight-classes-explained', 'protein-sources-compared',
  'protein-tracking-apps-compared', 'reading-nutrition-labels',
  'salary-cap-basics-for-gm-games', 'snake-draft-vs-auction-draft',
  'sports-gm-games-without-internet', 'thai-tones-explained',
  'understanding-sports-sim-probability', 'video-codecs-explained',
  'video-file-formats-explained', 'wave-survival-game-design',
  'what-is-a-ketone-reading', 'what-makes-a-good-draft-board',
  'what-makes-a-roguelike', 'working-memory-and-training',
]);

const RELEASE_DATE = '2026-09-04';

/** Cluster labels, derived from category plus the primary app's subject. */
const CLUSTER = {
  'sports-gm': 'Sports career & GM',
  'language-learning': 'Language learning',
  'health-nutrition': 'Health & nutrition',
  'education-brain': 'Education & brain training',
  'anime-creative': 'Anime & creative',
  'action-arcade': 'Action & arcade',
  'video-utility': 'Video & utility',
};

const articles = readdirSync(CONTENT)
  .filter((f) => f.endsWith('.md'))
  .map((file) => {
    const slug = file.replace(/\.md$/, '');
    const raw = readFileSync(join(CONTENT, file), 'utf8');
    const m = FRONTMATTER.exec(raw);
    const data = JSON.parse(m[1]);
    return { slug, ...data, words: raw.slice(m[0].length).trim().split(/\s+/).length };
  });

const releasedNow = articles.filter((a) => a.publishedAt === RELEASE_DATE);
const formerlyGated = releasedNow.filter((a) => PREVIOUSLY_GATED.has(a.slug));
const newlyWritten = releasedNow.filter((a) => !PREVIOUSLY_GATED.has(a.slug));
const preExisting = articles.filter((a) => a.publishedAt !== RELEASE_DATE);

const esc = (s) => String(s).replace(/\|/g, '\\|');
const table = (list) => [
  '| # | Title | Slug | Category | Primary app | Intent | Words |',
  '| ---: | --- | --- | --- | --- | --- | ---: |',
  ...list
    .sort((a, b) => a.category.localeCompare(b.category) || a.slug.localeCompare(b.slug))
    .map(
      (a, i) =>
        `| ${i + 1} | ${esc(a.title)} | \`${a.slug}\` | ${CLUSTER[a.category]} | \`${a.relatedApps[0]}\` | ${a.intent} | ${a.words} |`
    ),
];

const lines = [
  '# Article inventory',
  '',
  '_Generated by `node scripts/build-article-inventory.mjs` from article',
  'frontmatter. Do not edit by hand._',
  '',
  `**${articles.length} published articles**: ${preExisting.length} published before this pass,`,
  `${formerlyGated.length} previously gated drafts released, ${newlyWritten.length} newly written.`,
  '',
  `## Previously gated drafts released on ${RELEASE_DATE} (${formerlyGated.length})`,
  '',
  'Each was reviewed against `docs/content-review-process.md` before release:',
  'app claims re-verified against the live Play listing, every source URL',
  'checked, category compliance rules applied, and internal links completed.',
  '',
  ...table(formerlyGated),
  '',
  `## Newly written and published on ${RELEASE_DATE} (${newlyWritten.length})`,
  '',
  ...table(newlyWritten),
  '',
  `## Published before this pass (${preExisting.length})`,
  '',
  'Original publication dates preserved. `updatedAt` was moved only for the',
  'articles that were meaningfully revised — see the final report.',
  '',
  ...table(preExisting),
  '',
];

writeFileSync(join(ROOT, 'docs', 'article-inventory.md'), lines.join('\n'), 'utf8');
console.log(
  `wrote article-inventory.md — ${preExisting.length} pre-existing, ${formerlyGated.length} released drafts, ${newlyWritten.length} new`
);
