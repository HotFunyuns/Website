/**
 * Derives docs/keyword-map.csv and docs/keyword-verification-needed.md from the
 * frontmatter of every article in content/blog.
 *
 * The map is generated rather than hand-maintained so it cannot drift from the
 * articles it describes. Nothing here is a measurement: we hold no search
 * volume, difficulty or CPC data, and the demand tiers are explicitly labelled
 * as unverified planning estimates.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = join(ROOT, 'content', 'blog');
const DOCS = join(ROOT, 'docs');

const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/;

if (!existsSync(CONTENT)) {
  console.error('build-keyword-map: content/blog not found.');
  process.exit(1);
}
mkdirSync(DOCS, { recursive: true });

const articles = readdirSync(CONTENT)
  .filter((file) => file.endsWith('.md'))
  .map((file) => {
    const raw = readFileSync(join(CONTENT, file), 'utf8');
    const match = FRONTMATTER.exec(raw);
    if (!match) throw new Error(`${file}: missing frontmatter`);
    return { slug: file.replace(/\.md$/, ''), data: JSON.parse(match[1]) };
  })
  .sort((a, b) => a.data.category.localeCompare(b.data.category) || a.slug.localeCompare(b.slug));

const COLUMNS = [
  'article_slug',
  'article_url',
  'status',
  'category',
  'primary_app',
  'primary_keyword',
  'secondary_keywords',
  'long_tail_keywords',
  'comparison_keywords',
  'question_keywords',
  'intent',
  'demand_tier_estimate',
  'internal_links',
  'verification_status',
];

const cell = (value) => {
  const text = Array.isArray(value) ? value.join(' | ') : String(value ?? '');
  return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
};

const rows = articles.map(({ slug, data }) => {
  const questions = [...(data.aiSearchQuestions ?? []), ...(data.faqs ?? []).map((f) => f.question)];
  const links = [
    ...(data.relatedApps ?? []).map((a) => `/apps/${a}/`),
    ...(data.relatedArticles ?? []).map((a) => `/blog/${a}/`),
    `/blog/category/${data.category}/`,
  ];

  return [
    slug,
    `/blog/${slug}/`,
    data.status,
    data.category,
    data.relatedApps?.[0] ?? '',
    data.primaryKeyword,
    data.secondaryKeywords ?? [],
    data.longTailKeywords ?? [],
    data.comparisonKeywords ?? [],
    [...new Set(questions)],
    data.intent,
    data.demandTier ?? 'unverified-unrated',
    [...new Set(links)],
    'UNVERIFIED — needs Keyword Planner / Semrush / Ahrefs',
  ].map(cell);
});

writeFileSync(
  join(DOCS, 'keyword-map.csv'),
  [COLUMNS.join(','), ...rows.map((r) => r.join(','))].join('\n') + '\n',
  'utf8'
);

/* ------------------------------------------------- verification-needed report */

const terms = new Map();
const record = (term, kind, slug) => {
  const key = term.trim().toLowerCase();
  if (!key) return;
  if (!terms.has(key)) terms.set(key, { kind, articles: new Set() });
  terms.get(key).articles.add(slug);
};

for (const { slug, data } of articles) {
  record(data.primaryKeyword, 'primary', slug);
  for (const term of data.secondaryKeywords ?? []) record(term, 'secondary', slug);
  for (const term of data.longTailKeywords ?? []) record(term, 'long-tail', slug);
  for (const term of data.comparisonKeywords ?? []) record(term, 'comparison', slug);
}

const collisions = [...terms.entries()].filter(([, v]) => v.articles.size > 1);
const sorted = [...terms.entries()].sort(([a], [b]) => a.localeCompare(b));

const report = [
  '# Keyword verification backlog',
  '',
  '_Generated by `node scripts/build-keyword-map.mjs`. Do not edit by hand._',
  '',
  'Every term below was chosen from topic knowledge and the app catalog. **None of',
  'them have been checked against a keyword tool.** We hold no search volume,',
  'difficulty, CPC or competition data for any of them, and this site publishes',
  'none. Before anyone plans work around these terms, run them through Google',
  'Keyword Planner, Semrush or Ahrefs and record the real figures somewhere other',
  'than this file.',
  '',
  `**${terms.size} unique terms across ${articles.length} articles.**`,
  '',
  '## Priority order for verification',
  '',
  '1. `primary` terms — one article is committed to each, so a bad choice is the',
  '   most expensive kind.',
  '2. `comparison` terms — commercial intent, and the articles behind them carry',
  '   the heaviest compliance requirements.',
  '3. `secondary` and `long-tail` terms — cheap to re-target later.',
  '',
];

if (collisions.length > 0) {
  report.push(
    '## Overlaps to review',
    '',
    'These terms appear in more than one article. Primary-keyword collisions are',
    'rejected at build time, so anything listed here is a secondary or long-tail',
    'overlap — usually fine, but worth a look for cannibalisation.',
    ''
  );
  for (const [term, info] of collisions) {
    report.push(`- \`${term}\` — ${[...info.articles].join(', ')}`);
  }
  report.push('');
}

report.push('## All terms', '', '| Term | Role | Articles | Status |', '| --- | --- | --- | --- |');
for (const [term, info] of sorted) {
  report.push(`| ${term} | ${info.kind} | ${[...info.articles].join(', ')} | unverified |`);
}
report.push('');

writeFileSync(join(DOCS, 'keyword-verification-needed.md'), report.join('\n'), 'utf8');

console.log(
  `keyword map: ${articles.length} articles, ${terms.size} unique terms, ${collisions.length} overlap(s)`
);
console.log('  docs/keyword-map.csv');
console.log('  docs/keyword-verification-needed.md');
