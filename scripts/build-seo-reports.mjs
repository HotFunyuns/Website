// Generates the keyword-to-URL map, the search-intent and cannibalisation map,
// and the structured-data report from the articles and the built output.
//
// Everything here is derived rather than written by hand, so the reports cannot
// drift from the content they describe. If a number in one of these files looks
// wrong, the fix is in the source it was derived from.
//
// Run: node scripts/build-seo-reports.mjs

import { readFileSync, readdirSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const CONTENT = join(ROOT, 'content', 'blog');
const DOCS = join(ROOT, 'docs');
const OUT = join(ROOT, 'out');
const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/;
const today = new Date().toLocaleDateString('en-CA', { timeZone: 'America/Los_Angeles' });

const articles = readdirSync(CONTENT)
  .filter((f) => f.endsWith('.md'))
  .map((file) => {
    const slug = file.replace(/\.md$/, '');
    const raw = readFileSync(join(CONTENT, file), 'utf8');
    const m = FRONTMATTER.exec(raw);
    const data = JSON.parse(m[1]);
    const body = raw.slice(m[0].length).trim();
    return {
      slug,
      ...data,
      words: body.split(/\s+/).length,
      internalArticleLinks: new Set([...body.matchAll(/\]\((\/blog\/[^)\s]+)\)/g)].map((x) => x[1])).size,
      appLinks: new Set([...body.matchAll(/\]\((\/apps\/[^)\s]+)\)/g)].map((x) => x[1])).size,
    };
  })
  .sort((a, b) => a.category.localeCompare(b.category) || a.slug.localeCompare(b.slug));

const published = articles.filter((a) => a.status === 'published');
const esc = (s) => String(s).replace(/\|/g, '\\|');

/* -------------------------------------------------- keyword-to-URL map */

const byCategory = {};
for (const a of published) (byCategory[a.category] ??= []).push(a);

const keywordMap = [
  '# Keyword-to-URL map',
  '',
  '_Generated by `node scripts/build-seo-reports.mjs` from article frontmatter.',
  'Do not edit by hand — edit the articles._',
  '',
  `**${published.length} published articles, ${published.length} distinct primary keywords.**`,
  '',
  'One article owns each primary keyword. The build refuses to compile if two',
  'articles claim the same one, so a collision cannot reach this table.',
  '',
  '**No search volume, difficulty or CPC appears here**, because no tool data',
  'exists for these terms. See `docs/keyword-research-100.md` for what evidence',
  'was actually collected and what it does and does not establish.',
  '',
];

for (const [category, list] of Object.entries(byCategory).sort()) {
  keywordMap.push(`## ${category} (${list.length})`, '');
  keywordMap.push('| Primary keyword | Intent | URL | Primary app | Words |');
  keywordMap.push('| --- | --- | --- | --- | ---: |');
  for (const a of list) {
    keywordMap.push(
      `| ${esc(a.primaryKeyword)} | ${a.intent} | \`/blog/${a.slug}/\` | \`${a.relatedApps[0]}\` | ${a.words} |`
    );
  }
  keywordMap.push('');
}

writeFileSync(join(DOCS, 'keyword-to-url-map.md'), keywordMap.join('\n'), 'utf8');

/* ------------------------------- search-intent and cannibalisation map */

// Two articles cannibalise when they compete for the same intent, not merely
// when they share a word.
//
// A raw token overlap is useless here, because our keywords are built from a
// shared frame: "learn lao for beginners" and "learn malay for beginners" share
// three of four tokens and are not remotely the same query — the language name
// is doing all the work. So tokens are weighted by inverse document frequency
// across the corpus of primary keywords. A token appearing in many keywords
// ("learn", "explained", "how") contributes almost nothing to similarity; a
// token appearing in one or two ("lao", "whip", "icing") contributes almost
// everything. That makes the measure sensitive to the part that distinguishes
// the query rather than to the part that all our queries share.
const tokens = (s) => s.toLowerCase().split(/[^a-z0-9]+/).filter((t) => t.length > 2);

const documentFrequency = new Map();
for (const a of published) {
  for (const t of new Set(tokens(a.primaryKeyword))) {
    documentFrequency.set(t, (documentFrequency.get(t) ?? 0) + 1);
  }
}
const idf = (t) => Math.log(published.length / (documentFrequency.get(t) ?? 1));

const similarity = (a, b) => {
  const A = new Set(tokens(a));
  const B = new Set(tokens(b));
  const union = new Set([...A, ...B]);
  let shared = 0;
  let total = 0;
  for (const t of union) {
    const w = idf(t);
    total += w;
    if (A.has(t) && B.has(t)) shared += w;
  }
  return total === 0 ? 0 : shared / total;
};

// 0.5 means half the *distinguishing* weight of the two queries is shared,
// which is where a pair starts to look like it competes for one result slot.
const CANNIBALISATION_THRESHOLD = 0.5;

// A high score is not automatically a problem, and the distinction that matters
// is structural rather than statistical.
//
// When each keyword contains a content token the other lacks — "baseball" vs
// "hockey", "batting" vs "draft" — the two queries name different subjects. A
// searcher typing one is not served by the other, so this is a parallel series:
// the same question asked about different things, which is a legitimate
// structure rather than two pages chasing one result.
//
// The dangerous shape is the opposite one: when one keyword's tokens are a
// subset of the other's, the broader page can absorb the narrower page's query,
// and one of them should be merged or retargeted. That is what REVIEW marks.
const classify = (a, b) => {
  const A = new Set(tokens(a));
  const B = new Set(tokens(b));
  const onlyA = [...A].filter((t) => !B.has(t));
  const onlyB = [...B].filter((t) => !A.has(t));

  if (onlyA.length > 0 && onlyB.length > 0) {
    return {
      verdict: 'parallel series',
      detail: `distinct subjects: ${onlyA.map((t) => `\`${t}\``).join(' ')} vs ${onlyB.map((t) => `\`${t}\``).join(' ')}`,
    };
  }
  return {
    verdict: 'REVIEW',
    detail: 'one keyword is a subset of the other — the broader page may absorb the narrower query',
  };
};

const risks = [];
for (let i = 0; i < published.length; i++) {
  for (let j = i + 1; j < published.length; j++) {
    const a = published[i];
    const b = published[j];
    if (a.category !== b.category || a.intent !== b.intent) continue;
    const score = similarity(a.primaryKeyword, b.primaryKeyword);
    if (score >= CANNIBALISATION_THRESHOLD) risks.push({ a, b, score, ...classify(a.primaryKeyword, b.primaryKeyword) });
  }
}
risks.sort((x, y) => (x.verdict === y.verdict ? y.score - x.score : x.verdict === 'REVIEW' ? -1 : 1));

const secondaryOverlap = new Map();
for (const a of published) {
  for (const term of a.secondaryKeywords ?? []) {
    const key = term.toLowerCase().trim();
    (secondaryOverlap.get(key) ?? secondaryOverlap.set(key, []).get(key)).push(a.slug);
  }
}

const intentCounts = {};
for (const a of published) intentCounts[a.intent] = (intentCounts[a.intent] ?? 0) + 1;

const intentMap = [
  '# Search-intent and cannibalisation map',
  '',
  '_Generated by `node scripts/build-seo-reports.mjs`. Do not edit by hand._',
  '',
  `Measured **${today}** across ${published.length} published articles.`,
  '',
  '## Intent distribution',
  '',
  '| Intent | Articles |',
  '| --- | ---: |',
  ...Object.entries(intentCounts)
    .sort((a, b) => b[1] - a[1])
    .map(([k, v]) => `| ${k} | ${v} |`),
  '',
  '## How duplication is prevented',
  '',
  '1. **Primary keyword uniqueness is a build gate.** `src/lib/blog/index.ts`',
  '   throws if two articles claim the same `primaryKeyword`, so the build fails',
  '   rather than shipping the collision.',
  '2. **Identical intent keys are a pre-flight failure.** `scripts/preflight-articles.mjs`',
  '   rejects two articles sharing a category, an intent and a normalised primary',
  '   keyword.',
  '3. **Near-duplicate titles are a pre-flight failure**, at 85% token overlap.',
  '4. **Duplicate titles, descriptions and canonicals are an output failure.**',
  '   `scripts/audit-output.mjs` checks the rendered HTML, which is the only',
  '   place a duplicate would actually matter.',
  '',
  '## Primary-keyword proximity within the same category and intent',
  '',
  'Similarity is weighted by inverse document frequency across all primary',
  'keywords, so a shared generic word counts for little and a shared distinctive',
  'one counts for a lot. A pair is listed when half or more of the combined',
  'distinguishing weight of the two queries is shared.',
  '',
  risks.length === 0
    ? 'No pair of published articles reaches that threshold within the same category and intent.'
    : 'Pairs above the threshold, for review:',
  '',
];

if (risks.length) {
  intentMap.push('| Article A | Article B | Weighted similarity | Verdict |', '| --- | --- | ---: | --- |');
  for (const { a, b, score, verdict, detail } of risks) {
    intentMap.push(
      `| \`${a.slug}\`<br>_${esc(a.primaryKeyword)}_ | \`${b.slug}\`<br>_${esc(b.primaryKeyword)}_ | ${(score * 100).toFixed(0)}% | ${verdict} — ${detail} |`
    );
  }
  const needsReview = risks.filter((r) => r.verdict === 'REVIEW').length;
  intentMap.push(
    '',
    `${risks.length - needsReview} of ${risks.length} pair(s) are parallel series — the same question asked`,
    'about a different subject, which is a legitimate structure rather than two',
    `articles chasing one result. ${needsReview} pair(s) are marked REVIEW.`,
    ''
  );
}

const sharedSecondary = [...secondaryOverlap.entries()].filter(([, slugs]) => slugs.length > 1);
intentMap.push(
  '## Secondary-keyword overlap',
  '',
  `${sharedSecondary.length} secondary term(s) appear on more than one article. Secondary`,
  'overlap is expected and usually harmless: it means two articles touch a shared',
  'concept from different angles. It is listed so a reviewer can spot the cases',
  'where it is not.',
  ''
);
if (sharedSecondary.length) {
  intentMap.push('| Term | Articles |', '| --- | --- |');
  for (const [term, slugs] of sharedSecondary.sort()) {
    intentMap.push(`| ${esc(term)} | ${slugs.map((s) => `\`${s}\``).join(', ')} |`);
  }
  intentMap.push('');
}

writeFileSync(join(DOCS, 'search-intent-and-cannibalization-map.md'), intentMap.join('\n'), 'utf8');

/* -------------------------------------------------- structured-data report */

if (existsSync(OUT)) {
  function walk(dir) {
    const found = [];
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) found.push(...walk(full));
      else if (full.endsWith('.html')) found.push(full);
    }
    return found;
  }

  const counts = {};
  const byRoute = {};
  for (const file of walk(OUT)) {
    const route = `/${file.slice(OUT.length + 1).split('\\').join('/').replace(/index\.html$/, '')}`;
    const doc = readFileSync(file, 'utf8');
    const types = [];
    for (const m of doc.matchAll(/<script type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/g)) {
      try {
        const type = JSON.parse(m[1].replace(/\\u003c/g, '<'))['@type'];
        counts[type] = (counts[type] ?? 0) + 1;
        types.push(type);
      } catch {
        /* validate-structured-data.mjs is the gate for this; here we only count */
      }
    }
    byRoute[route] = types;
  }

  const sample = (pattern) => Object.entries(byRoute).find(([r]) => pattern.test(r));

  const schemaReport = [
    '# Structured-data report',
    '',
    '_Generated by `node scripts/build-seo-reports.mjs` from the exported `out/`',
    'directory, and validated by `node scripts/validate-structured-data.mjs`._',
    '',
    `Measured **${today}**.`,
    '',
    '## Types emitted',
    '',
    '| Type | Blocks |',
    '| --- | ---: |',
    ...Object.entries(counts)
      .sort((a, b) => b[1] - a[1])
      .map(([k, v]) => `| ${k} | ${v} |`),
    '',
    '## Per page type',
    '',
    '| Page type | Types emitted |',
    '| --- | --- |',
    `| Homepage | ${(byRoute['/'] ?? []).join(', ')} |`,
    `| App page | ${(sample(/^\/apps\/[^/]+\/$/) ?? ['', []])[1].join(', ')} |`,
    `| Article | ${(sample(/^\/blog\/[^/]+\/$/) ?? ['', []])[1].join(', ')} |`,
    `| Blog index | ${(byRoute['/blog/'] ?? []).join(', ')} |`,
    `| Category | ${(sample(/^\/blog\/category\//) ?? ['', []])[1].join(', ')} |`,
    '',
    '## What is deliberately absent',
    '',
    'The validator fails the build if any of these appear, because we hold no',
    'verified source for them:',
    '',
    '- `aggregateRating` — no star ratings are published anywhere on this site.',
    '- `review` and `reviewCount` — we have no reviews to mark up.',
    '- `ratingValue` — same.',
    '- `award` — we have not received any.',
    '',
    '## Rules the validator enforces',
    '',
    '1. Every JSON-LD block parses, and carries `@context` or `@id`.',
    '2. Each type has the fields Google documents as required for it.',
    '3. Every `FAQPage` question also appears in the visible page text.',
    '4. Every `BlogPosting` `citation` URL is also a visible, clickable link on',
    '   the page — structured data may not assert a source a reader cannot see.',
    '5. `SoftwareApplication.installUrl` is a Google Play listing URL.',
    '6. An `Offer` may only declare `price: "0"`, matching the verified listing.',
    '7. `dateModified` never precedes `datePublished`.',
    '',
    '## Live validation',
    '',
    "Google's Rich Results Test needs a public URL, so it runs after deploy",
    'rather than in this pass. Representative URLs to submit:',
    '',
    '- `https://reigncreativellc.com/` — Organization, WebSite',
    '- `https://reigncreativellc.com/apps/baseball-career-sim/` — SoftwareApplication, BreadcrumbList, FAQPage',
    '- `https://reigncreativellc.com/blog/baseball-career-sim-guide/` — BlogPosting, BreadcrumbList, FAQPage',
    '',
  ];

  writeFileSync(join(DOCS, 'structured-data-report.md'), schemaReport.join('\n'), 'utf8');
}

console.log(`wrote keyword-to-url-map.md (${published.length} articles)`);
console.log(`wrote search-intent-and-cannibalization-map.md (${risks.length} proximity pair(s))`);
if (existsSync(OUT)) console.log('wrote structured-data-report.md');
